package eval

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"time"
)

// LocalRunPaths holds the per-suite/scenario directory layout for a
// local-mode flow-eval run. Workdir lives under /tmp so an accidental
// CleanupProject rm-rf cannot reach the source repo or operator $HOME;
// results land back inside the source tree (eval/behavioral/runs-local/)
// for easy inspection.
type LocalRunPaths struct {
	SuiteID     string // YYYYMMDD-HHMMSS
	ScenarioID  string // matches scenario file basename
	WorkDir     string // /tmp/zcp-flow-eval-local/<suite>/<scenario>/workdir
	ClaudeHome  string // /tmp/zcp-flow-eval-local/<suite>/<scenario>/claude-home
	ResultsDir  string // <repo>/eval/behavioral/runs-local
	Sentinel    string // <WorkDir>/.zcp-eval-workdir
	ScenarioDir string // <repo>/eval/behavioral/scenarios-local (default)
}

// SentinelFilename is the marker file the local-mode wrapper writes into
// each workdir. CleanupProject (gated by ZCP_EVAL_SENTINEL_FILE) checks
// for this so a misconfigured ZCP_EVAL_WORK_DIR cannot trigger a
// destructive cleanup against the operator's real data.
const SentinelFilename = ".zcp-eval-workdir"

// LocalRunRoot is the base directory under /tmp where local-mode eval
// scratch state lives. Fixed prefix so accumulated runs are easy to
// inspect or wipe (`rm -rf /tmp/zcp-flow-eval-local/`).
const LocalRunRoot = "/tmp/zcp-flow-eval-local"

// ComputeLocalRunPaths builds the directory layout for one local-mode
// scenario run. suiteID is generated by the caller (typically the
// timestamp from time.Now). repoRoot is the absolute path to the zcp
// source tree (results land relative to it so the local Claude session
// can read them later).
func ComputeLocalRunPaths(suiteID, scenarioID, repoRoot string) LocalRunPaths {
	scenarioRoot := filepath.Join(LocalRunRoot, suiteID, scenarioID)
	workDir := filepath.Join(scenarioRoot, "workdir")
	return LocalRunPaths{
		SuiteID:     suiteID,
		ScenarioID:  scenarioID,
		WorkDir:     workDir,
		ClaudeHome:  filepath.Join(scenarioRoot, "claude-home"),
		ResultsDir:  filepath.Join(repoRoot, "eval", "behavioral", "runs-local"),
		Sentinel:    filepath.Join(workDir, SentinelFilename),
		ScenarioDir: filepath.Join(repoRoot, "eval", "behavioral", "scenarios-local"),
	}
}

// NewSuiteID returns the timestamp suite identifier the runs use:
// YYYYMMDD-HHMMSS in UTC, matching what behavioral_run.go emits on stderr.
func NewSuiteID() string {
	return time.Now().UTC().Format("20060102-150405")
}

// PrepareLocalRunDirs creates workdir + claude-home + results-dir and
// writes the sentinel into workdir. Idempotent — re-running on existing
// dirs leaves them alone (mkdir -p semantics).
func PrepareLocalRunDirs(p LocalRunPaths) error {
	for _, dir := range []string{p.WorkDir, p.ClaudeHome, p.ResultsDir} {
		if err := os.MkdirAll(dir, 0o700); err != nil {
			return fmt.Errorf("mkdir %s: %w", dir, err)
		}
	}
	if err := os.WriteFile(p.Sentinel, []byte(""), 0o644); err != nil {
		return fmt.Errorf("write sentinel %s: %w", p.Sentinel, err)
	}
	return nil
}

// AssertLocalRunPrereqs checks the three operator-side preconditions for
// a local-mode flow-eval run. The error messages are written for an
// operator who hits the problem at the CLI — actionable, no internal
// jargon, point at the fix.
//
// Order matters: ZCP_API_KEY before zcp-on-PATH because a missing token
// is a more common operator setup miss; reporting it first avoids
// telling them to run `make install` when their real problem is the
// token export.
func AssertLocalRunPrereqs() error {
	if os.Getenv("ZCP_API_KEY") == "" {
		return fmt.Errorf(`ZCP_API_KEY env var is required for local-mode flow-eval.
Set it to your eval-zcp project-scoped token (the one in your .mcp.json
and matching what 'zcli login' is using). Example:
  export ZCP_API_KEY=<eval-zcp-token>
The token authenticates BOTH the parent eval runner (for service
cleanup + fixture import) AND the spawned MCP server inside the agent's
claude process (via env inheritance).`)
	}
	if _, err := exec.LookPath("zcp"); err != nil {
		return fmt.Errorf(`'zcp' not found in PATH — local-mode flow-eval needs the
binary installed (the spawned claude process resolves command:"zcp" via
PATH). Install with:
  make install
Then re-run.`)
	}
	return nil
}

// PrepareIsolatedClaudeHome creates an isolated HOME for the agent's
// `claude` process so the eval doesn't read or pollute the operator's
// real ~/.claude/ (auto-memory, sessions, settings, plugins, slash
// commands). It builds an empty .claude/ inside claudeHome and — if
// the operator has an OAuth credentials file at ~/.claude/.credentials.json —
// symlinks it through so the eval can authenticate Anthropic without
// forcing the operator to set ANTHROPIC_API_KEY (which `--bare` would
// require).
//
// Why symlink instead of copy: token refresh writes by claude propagate
// to the real file rather than diverging.
//
// Idempotent: re-running on an existing claudeHome is safe (existing
// symlink target is left alone via os.Symlink's EEXIST behavior).
func PrepareIsolatedClaudeHome(claudeHome string) error {
	if claudeHome == "" {
		return fmt.Errorf("claudeHome is required")
	}
	sandboxClaude := filepath.Join(claudeHome, ".claude")
	if err := os.MkdirAll(sandboxClaude, 0o700); err != nil {
		return fmt.Errorf("mkdir sandbox .claude: %w", err)
	}
	realHome, err := os.UserHomeDir()
	if err != nil {
		// No operator home — skip credential symlink (eval will need
		// ANTHROPIC_API_KEY in env to auth).
		return nil
	}
	realCreds := filepath.Join(realHome, ".claude", ".credentials.json")
	if _, err := os.Stat(realCreds); err != nil {
		// Operator has no OAuth file (e.g. uses ANTHROPIC_API_KEY directly).
		// Eval will need that env var; nothing to symlink.
		return nil
	}
	sandboxCreds := filepath.Join(sandboxClaude, ".credentials.json")
	if _, err := os.Lstat(sandboxCreds); err == nil {
		// Already exists (idempotent re-run) — leave alone.
		return nil
	}
	if err := os.Symlink(realCreds, sandboxCreds); err != nil {
		return fmt.Errorf("symlink credentials: %w", err)
	}
	return nil
}
